import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const source = fs.readFileSync(new URL('../app/revision-location.ts', import.meta.url), 'utf8');
const box = {};
new Function('exports', ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText)(box);
const locate = box.locateRevisedPassage;
const target = 'Many students is using AI without checking the answer careful, and teh feedback can be confusing.';
const before = 'Our class discusses responsible technology use.';
const after = 'Teachers encourage everyone to review each suggestion independently.';
const original = `${before}\n\n${target}\n\n${after}`;
let checks = 0;
function found(text, expected, quote = target, draft = original, start) {
  const range = locate(draft, text, quote, start);
  assert.ok(range, `Expected a location: ${expected}`);
  assert.equal(text.slice(range.start, range.end), expected);
  checks++;
}
found(original, target);
found(original, target, 'students is');
const fixed = target.replace('students is', 'students are').replace('careful,', 'carefully,').replace('teh', 'the');
found(original.replace(target, fixed), fixed);
found('A new introduction explains the activity.\n' + original.replace(target, fixed), fixed);
found(original.replace(before, '').replace(target, fixed), fixed);
found(original.replace(target, target.replace('using AI', 'using a new AI tool')), target.replace('using AI', 'using a new AI tool'));
const split = fixed.replace(', and the', '. The');
found(original.replace(target, split), split);
const rewritten = 'This experience has changed my approach to independent study entirely.';
assert.equal(locate(original, original.replace(target, rewritten), target), null); checks++;
assert.equal(locate(original, `${before}\n\n${after}`, target), null); checks++;
assert.equal(locate(original, '', target), null); checks++;
assert.equal(locate(original, original, 'not present'), null); checks++;
assert.equal(locate(original, original, target, 0), null); checks++;
const repeated = `${before} ${target} ${after} ${target}`;
assert.equal(locate(repeated, repeated, target), null); checks++;
found(repeated, target, target, repeated, repeated.lastIndexOf(target));
const modifiedRepeat = repeated.slice(0, repeated.lastIndexOf(target)) + fixed;
found(modifiedRepeat, fixed, target, repeated, repeated.lastIndexOf(target));
assert.equal(locate(`${target} ${target}`, fixed, target, 0), null); checks++;
const ambiguous = `${before} ${fixed} ${after} ${before} ${fixed} ${after}`;
assert.equal(locate(original, ambiguous, target), null); checks++;
found(`${fixed} ${before} ${after}`, fixed);
const unicode = `🙂 Students’ notes include café examples.\r\n${target}\r\n${after}`;
found(unicode.replace(target, fixed), fixed, target, unicode);
const longPrefix = Array.from({ length: 65 }, (_, i) => `Section ${i + 1} describes a separate classroom activity with clear instructions.`).join('\n');
const long = `${longPrefix}\n${original}`;
const started = performance.now();
for (let i = 0; i < 10; i++) found(long.replace(target, fixed), fixed, target, long);
assert.ok(performance.now() - started < 1500, 'Long drafts must not make every keystroke expensive');
// Text is returned only as offsets; literal markup is never HTML-interpreted.
const literal = 'A student writes <img onerror="alert(1)"> as a literal example.';
found(literal, literal, literal, literal);
const editor = fs.readFileSync(new URL('../app/linked-revision-editor.tsx', import.meta.url), 'utf8');
assert.doesNotMatch(editor, /fetch\(|setSelectionRange|\.focus\(|dangerouslySetInnerHTML|contentEditable/);
assert.match(editor, /lastNavigation\.current === navigationId/);
assert.match(editor, /document\.activeElement === input/);
assert.match(editor, /mark\.getBoundingClientRect\(\)/);
assert.match(editor, /onScroll=\{syncScroll\}/);
assert.match(editor, /aria-hidden="true"/);
assert.match(editor, /暂时无法可靠定位/);
console.log(`Revision-location checks passed: ${checks} matching cases, long-draft timing, ambiguity/deletion controls and non-mutating editor contract. No AI calls.`);
