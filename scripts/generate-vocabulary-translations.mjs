import { readFile, writeFile } from "node:fs/promises";
import { customFallbackWords, curatedKeywordBank } from "../app/data.ts";

function loadLocalKey() {
  return readFile(new URL("../.env.local", import.meta.url), "utf8").then((content) => {
    const line = content.split(/\r?\n/).find((candidate) => candidate.startsWith("OPENAI_API_KEY="));
    return line?.slice("OPENAI_API_KEY=".length).trim().replace(/^['\"]|['\"]$/g, "") ?? "";
  });
}

function extractOutputText(data) {
  if (typeof data.output_text === "string") return data.output_text;
  for (const item of Array.isArray(data.output) ? data.output : []) {
    for (const part of Array.isArray(item?.content) ? item.content : []) {
      if (typeof part?.text === "string") return part.text;
    }
  }
  return "";
}

const words = [...new Set([
  ...Object.values(curatedKeywordBank).flat(),
  ...customFallbackWords,
].map((word) => word.toLowerCase()))].sort();
const apiKey = await loadLocalKey();
if (!apiKey) throw new Error("OPENAI_API_KEY is missing from .env.local");

const translations = {};
const batchSize = 100;
for (let start = 0; start < words.length; start += batchSize) {
  const batch = words.slice(start, start + batchSize);
  const response = await fetch("https://api.openai.com/v1/responses", {
    method: "POST",
    headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
    body: JSON.stringify({
      model: process.env.OPENAI_MODEL || "gpt-5.4-mini",
      store: false,
      instructions: "Translate every supplied English academic keyword into concise, accurate Simplified Chinese. Keep the English word exactly unchanged. Give only the most useful meaning for university academic writing. Hyphenated terms must be translated as a complete concept, not word by word. Do not omit or add entries.",
      input: JSON.stringify(batch),
      max_output_tokens: 6000,
      text: {
        verbosity: "low",
        format: {
          type: "json_schema",
          name: "keyword_translations",
          strict: true,
          schema: {
            type: "object",
            additionalProperties: false,
            properties: {
              items: {
                type: "array",
                minItems: batch.length,
                maxItems: batch.length,
                items: {
                  type: "object",
                  additionalProperties: false,
                  properties: { word: { type: "string" }, translation: { type: "string" } },
                  required: ["word", "translation"],
                },
              },
            },
            required: ["items"],
          },
        },
      },
    }),
  });
  if (!response.ok) throw new Error(`Translation request failed with ${response.status}`);
  const parsed = JSON.parse(extractOutputText(await response.json()));
  const returned = new Map(parsed.items.map((item) => [item.word, item.translation.trim()]));
  for (const word of batch) {
    const translation = returned.get(word);
    if (!translation || /[A-Za-z]{3}/.test(translation)) throw new Error(`Invalid or missing Chinese translation for ${word}`);
    translations[word] = translation;
  }
  console.log(`Translated ${Math.min(start + batch.length, words.length)} / ${words.length}`);
}

const output = `// Generated by scripts/generate-vocabulary-translations.mjs.\n// Do not edit individual entries without rerunning vocabulary validation.\nexport const keywordTranslations = ${JSON.stringify(translations, null, 2)};\n`;
await writeFile(new URL("../app/vocabulary-translations.generated.js", import.meta.url), output, "utf8");
console.log(`Saved ${words.length} validated Chinese translations.`);
